"""Measure WhereWas location estimates against a labelled image set.

CSV columns (required):
    image_path,true_lat,true_lon

``image_path`` may be absolute or relative to the CSV file.  Optional columns
such as ``id`` and ``split`` are retained in the per-image report.

The evaluator runs the same ``analyze_stream`` function used by the FastAPI
endpoint.  It never uploads images through the HTTP endpoint and never edits
or deletes the labelled source images.
"""

from __future__ import annotations

import argparse
import asyncio
import csv
import json
import math
import statistics
import sys
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from analyze.pipeline import analyze_stream

EARTH_RADIUS_M = 6_371_008.8
THRESHOLDS_KM = (1.0, 25.0, 200.0)


@dataclass(frozen=True)
class EvaluationItem:
    """One labelled place image from the evaluation CSV."""

    image_path: Path
    true_lat: float
    true_lon: float
    row: dict[str, str]


def haversine_m(lat_a: float, lon_a: float, lat_b: float, lon_b: float) -> float:
    """Great-circle distance in metres between two WGS84 latitude/longitudes."""
    phi_a, phi_b = math.radians(lat_a), math.radians(lat_b)
    d_phi = math.radians(lat_b - lat_a)
    d_lambda = math.radians(lon_b - lon_a)
    value = math.sin(d_phi / 2) ** 2 + math.cos(phi_a) * math.cos(phi_b) * math.sin(d_lambda / 2) ** 2
    return 2 * EARTH_RADIUS_M * math.asin(math.sqrt(value))


def read_items(csv_path: Path) -> list[EvaluationItem]:
    """Load and validate the evaluation CSV before making any network calls."""
    with csv_path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        required = {"image_path", "true_lat", "true_lon"}
        if not reader.fieldnames or not required.issubset(reader.fieldnames):
            raise ValueError("CSV must contain headers: image_path,true_lat,true_lon")
        items: list[EvaluationItem] = []
        for line_number, row in enumerate(reader, start=2):
            raw_path = (row.get("image_path") or "").strip()
            if not raw_path:
                raise ValueError(f"Row {line_number}: image_path is empty")
            image_path = Path(raw_path)
            if not image_path.is_absolute():
                image_path = csv_path.parent / image_path
            if not image_path.is_file():
                raise FileNotFoundError(f"Row {line_number}: image not found: {image_path}")
            try:
                lat, lon = float(row["true_lat"]), float(row["true_lon"])
            except (TypeError, ValueError) as exc:
                raise ValueError(f"Row {line_number}: true_lat and true_lon must be numbers") from exc
            if not (-90 <= lat <= 90 and -180 <= lon <= 180):
                raise ValueError(f"Row {line_number}: invalid WGS84 coordinate")
            items.append(EvaluationItem(image_path.resolve(), lat, lon, row))
    if not items:
        raise ValueError("CSV has no labelled images")
    return items


async def run_current_pipeline(image_path: Path, timeout_s: float) -> dict[str, Any]:
    """Return the final streamed result generated by the production pipeline."""
    async def collect() -> dict[str, Any]:
        async for raw_event in analyze_stream(image_path, image_path.name, "evaluation"):
            event = json.loads(raw_event)
            if event.get("type") == "result":
                return event["data"]
            if event.get("type") == "error":
                raise RuntimeError(event.get("message") or "Pipeline returned an unknown error")
        raise RuntimeError("Pipeline ended without a result")

    return await asyncio.wait_for(collect(), timeout=timeout_s)


def candidate_distances(result: dict[str, Any], item: EvaluationItem, top_k: int) -> list[dict[str, Any]]:
    """Attach ground-truth errors to valid candidates in their returned order."""
    distances: list[dict[str, Any]] = []
    for rank, candidate in enumerate((result.get("candidates") or [])[:top_k], start=1):
        try:
            lat, lon = float(candidate["lat"]), float(candidate["lon"])
        except (KeyError, TypeError, ValueError):
            continue
        distances.append(
            {
                "rank": rank,
                "name": candidate.get("name"),
                "source": candidate.get("source"),
                "tier": candidate.get("tier"),
                "score": candidate.get("score"),
                "radius_m": candidate.get("radius_m"),
                "lat": lat,
                "lon": lon,
                "error_m": round(haversine_m(item.true_lat, item.true_lon, lat, lon), 2),
            }
        )
    return distances


def percentage(numerator: int, denominator: int) -> float | None:
    return round(100 * numerator / denominator, 2) if denominator else None


def summarize(records: Iterable[dict[str, Any]]) -> dict[str, Any]:
    """Compute top-1 accuracy and top-10 recall without hiding failures."""
    records = list(records)
    completed = [record for record in records if record.get("status") == "ok"]
    top1_errors = [record["top1_error_m"] for record in completed if record.get("top1_error_m") is not None]
    summary: dict[str, Any] = {
        "images_total": len(records),
        "completed": len(completed),
        "failed": len(records) - len(completed),
        "with_top1_candidate": len(top1_errors),
        "median_top1_error_km": round(statistics.median(top1_errors) / 1000, 3) if top1_errors else None,
        "thresholds_km": {},
        "notes": [
            "Top-1 measures the first returned candidate. Top-10 measures whether any returned candidate is close to the ground truth.",
            "Failures and rows with no candidate count as misses at every threshold.",
            "Evaluate EXIF-bearing and EXIF-stripped images separately; otherwise embedded GPS can inflate the baseline.",
        ],
    }
    for threshold_km in THRESHOLDS_KM:
        threshold_m = threshold_km * 1000
        top1_hits = sum(1 for record in records if record.get("top1_error_m") is not None and record["top1_error_m"] <= threshold_m)
        top10_hits = sum(
            1
            for record in records
            if any(candidate["error_m"] <= threshold_m for candidate in record.get("candidates", []))
        )
        summary["thresholds_km"][str(int(threshold_km))] = {
            "top1_accuracy_percent": percentage(top1_hits, len(records)),
            "top10_recall_percent": percentage(top10_hits, len(records)),
            "top1_hits": top1_hits,
            "top10_hits": top10_hits,
        }
    return summary


async def evaluate(items: list[EvaluationItem], *, top_k: int, timeout_s: float) -> list[dict[str, Any]]:
    """Run sequentially to respect the existing public-geocoder rate limits."""
    records: list[dict[str, Any]] = []
    for position, item in enumerate(items, start=1):
        print(f"[{position}/{len(items)}] {item.image_path.name}", flush=True)
        started = time.monotonic()
        base = {
            "id": item.row.get("id") or item.image_path.stem,
            "image_path": str(item.image_path),
            "true_lat": item.true_lat,
            "true_lon": item.true_lon,
        }
        try:
            result = await run_current_pipeline(item.image_path, timeout_s)
            candidates = candidate_distances(result, item, top_k)
            records.append(
                {
                    **base,
                    "status": "ok",
                    "elapsed_s": round(time.monotonic() - started, 2),
                    "top1_error_m": candidates[0]["error_m"] if candidates else None,
                    "candidates": candidates,
                    "pipeline_summary": result.get("summary"),
                    "pipeline_elapsed_ms": result.get("elapsed_ms"),
                }
            )
        except Exception as exc:  # Keep one bad input/provider outage from losing the complete run.
            records.append({**base, "status": "failed", "elapsed_s": round(time.monotonic() - started, 2), "error": str(exc)})
            print(f"  failed: {exc}", file=sys.stderr, flush=True)
    return records


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Evaluate the current WhereWas pipeline against labelled place photographs.")
    parser.add_argument("csv", type=Path, help="CSV containing image_path,true_lat,true_lon")
    parser.add_argument("--output", type=Path, default=Path("evaluation-report.json"), help="JSON report path")
    parser.add_argument("--top-k", type=int, default=10, choices=range(1, 11), metavar="1..10", help="Number of returned candidates to assess")
    parser.add_argument("--timeout", type=float, default=90.0, help="Maximum seconds per image")
    return parser.parse_args()


async def main() -> None:
    args = parse_args()
    csv_path = args.csv.resolve()
    items = read_items(csv_path)
    records = await evaluate(items, top_k=args.top_k, timeout_s=args.timeout)
    report = {
        "schema_version": 1,
        "generated_at_unix": int(time.time()),
        "input_csv": str(csv_path),
        "top_k": args.top_k,
        "summary": summarize(records),
        "records": records,
    }
    output = args.output.resolve()
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, indent=2, ensure_ascii=False), encoding="utf-8")
    print("\nBaseline summary")
    print(json.dumps(report["summary"], indent=2))
    print(f"\nDetailed report: {output}")


if __name__ == "__main__":
    asyncio.run(main())
